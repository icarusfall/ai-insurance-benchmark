"""Export what the Mutually Assured AI Modelling site needs into public/data.js.

    python -m mutual_site.build

The defaults (with their ranges, basis and source ids), the whole parameter registry, the bio insurability
tests and grid as computed by the Python model, and the market lens with its Markets preset. The site's own model (public/model.js) recomputes everything else
in the browser; tests/test_mutual_site.py checks it against the Python model.
"""
import datetime
import glob
import json
import os

import yaml

from catmodel import frequency, insurability, markets, sensitivity
from catmodel.model import DEFAULTS

HERE = os.path.dirname(__file__)
OUT = os.path.join(HERE, "public", "data.js")
SOURCES = os.path.join(HERE, "..", "catmodel", "sources")


def registry() -> list:
    out = []
    for path in sorted(glob.glob(os.path.join(SOURCES, "*.yaml"))):
        with open(path, encoding="utf-8") as f:
            entries = yaml.safe_load(f)
            if not isinstance(entries, list):           # market_snapshot.yaml is data, not registry entries
                continue
            for e in entries:
                e["file"] = os.path.basename(path)
                out.append(e)
    return out


def main():
    with open(DEFAULTS, encoding="utf-8") as f:
        defaults = yaml.safe_load(f)
    data = dict(
        built=datetime.date.today().isoformat(),
        defaults=defaults,
        sources=registry(),
        bio=dict(criteria=[dict(zip(("criterion", "test", "result", "verdict", "fix"), r)) for r in insurability.criteria()],
                 grid=[{k: g[k] for k in ("alpha", "attribution", "limit", "el", "share_of_liability",
                                          "premium_share_revenue", "var995", "tvar995")} for g in insurability.grid()],
                 asset_drawdown=insurability.ASSET_DRAWDOWN, call_recovery=insurability.CALL_RECOVERY),
        markets=dict(snapshot=markets.load_snapshot(), **markets.implied()),
        sensitivity=sensitivity.sweep(),
        frequency=frequency.summary(),
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by python -m mutual_site.build. Do not edit by hand.\nwindow.MAIM = ")
        json.dump(data, f, separators=(",", ":"), default=str)
        f.write(";\n")
    print(f"wrote {OUT} ({os.path.getsize(OUT) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
