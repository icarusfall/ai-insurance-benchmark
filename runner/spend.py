"""Running tally of API spend, from every calls.jsonl under runs/ (games and preflights).

    python -m runner.spend            # print the tally
    python -m runner.spend --write    # also refresh results/SPEND.md (committed; runs/ is git-ignored)

Costs are as logged per call: provider-reported for OpenRouter, otherwise computed from models.yaml prices
(OpenAI and Gemini prices there are reference figures, so treat those totals as estimates).
"""
import argparse
import glob
import json
import os
import time
from collections import defaultdict


def calls(root: str = "runs"):
    for p in glob.glob(os.path.join(root, "**", "calls.jsonl"), recursive=True):
        rel = os.path.relpath(p, root).replace("\\", "/").split("/")
        batch = rel[0] if len(rel) > 2 else "single games"
        with open(p) as f:
            for line in f:
                try:
                    c = json.loads(line)
                except json.JSONDecodeError:
                    continue
                yield batch, c


def total(root: str = "runs") -> float:
    return sum(float(c.get("usd") or 0.0) for _, c in calls(root))


def tally(root: str = "runs") -> dict:
    by_batch, by_model, by_day = defaultdict(float), defaultdict(float), defaultdict(float)
    n = 0
    for batch, c in calls(root):
        usd = float(c.get("usd") or 0.0)
        by_batch[batch] += usd
        by_model[c.get("model", "?")] += usd
        by_day[time.strftime("%Y-%m-%d", time.localtime(c["ts"])) if c.get("ts") else "unknown"] += usd
        n += 1
    return dict(total=sum(by_batch.values()), calls=n, by_batch=by_batch, by_model=by_model, by_day=by_day)


def render(t: dict) -> str:
    L = ["# API spend", "", f"Updated {time.strftime('%Y-%m-%d %H:%M')}. Total **${t['total']:.2f}** over "
         f"{t['calls']:,} model calls. Generated by `python -m runner.spend --write` from the local run logs.", ""]
    for title, d in (("By batch", t["by_batch"]), ("By model", t["by_model"]), ("By day", t["by_day"])):
        L += [f"## {title}", "", "| | $ |", "|---|---|"]
        L += [f"| {k} | {v:.2f} |" for k, v in sorted(d.items(), key=lambda kv: (title == "By day" and kv[0]) or -kv[1])]
        L.append("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="runs")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    md = render(tally(a.root))
    print(md)
    if a.write:
        os.makedirs("results", exist_ok=True)
        with open(os.path.join("results", "SPEND.md"), "w", encoding="utf-8") as f:
            f.write(md + "\n")


if __name__ == "__main__":
    main()
